#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

CONTAINER_RUNTIME="${CONTAINER_RUNTIME:-podman}"
GENERATOR_IMAGE="${GENERATOR_IMAGE:-docker.io/openapitools/openapi-generator-cli:v7.12.0}"

CAMBOT_SPEC="/workspace/apps/contracts/openapi/cambot-api.yaml"
CAMERA_SPEC="/workspace/apps/contracts/openapi/camera-system-mocker-api.yaml"

run_generator() {
  "$CONTAINER_RUNTIME" run --rm \
    -v "$PROJECT_ROOT:/workspace" \
    "$GENERATOR_IMAGE" "$@"
}

reset_dir() {
  local dir="$1"
  rm -rf "$dir"
  mkdir -p "$dir"
}

echo "Validating OpenAPI specs..."
run_generator validate -i "$CAMBOT_SPEC"
run_generator validate -i "$CAMERA_SPEC"

echo "Generating Python DTO/client package for RestApi..."
reset_dir "$PROJECT_ROOT/apps/server/RestApi/dtos/cambot"
run_generator generate -i "$CAMBOT_SPEC" -g python \
  -o /workspace/apps/server/RestApi/dtos/cambot \
  --additional-properties=packageName=cambot_dtos,projectName=cambot-dtos

echo "Generating Python DTO/client packages for GeminiCaller..."
reset_dir "$PROJECT_ROOT/apps/server/GeminiCaller/dtos/cambot"
reset_dir "$PROJECT_ROOT/apps/server/GeminiCaller/dtos/camera_system"
run_generator generate -i "$CAMBOT_SPEC" -g python \
  -o /workspace/apps/server/GeminiCaller/dtos/cambot \
  --additional-properties=packageName=cambot_dtos,projectName=cambot-dtos
run_generator generate -i "$CAMERA_SPEC" -g python \
  -o /workspace/apps/server/GeminiCaller/dtos/camera_system \
  --additional-properties=packageName=camera_system_dtos,projectName=camera-system-dtos

echo "Generating Python DTO/client package for CameraSystemMockerRestApi..."
reset_dir "$PROJECT_ROOT/apps/server/CameraSystemMockerRestApi/dtos/camera_system"
run_generator generate -i "$CAMERA_SPEC" -g python \
  -o /workspace/apps/server/CameraSystemMockerRestApi/dtos/camera_system \
  --additional-properties=packageName=camera_system_dtos,projectName=camera-system-dtos

echo "Creating lightweight browser DTO helpers..."
mkdir -p "$PROJECT_ROOT/apps/client/dtos"

cat > "$PROJECT_ROOT/apps/client/dtos/camSystemDtos.js" <<'EOF'
// Code generated by apps/generate-dtos.sh.
// Source of truth: apps/contracts/openapi/camera-system-mocker-api.yaml

export function normalizeCamera(raw) {
  return {
    id: String(raw.id),
    name: String(raw.name),
    location: String(raw.location),
    status: String(raw.status),
    snapshotUrl: String(raw.snapshotUrl),
    tags: Array.isArray(raw.tags) ? raw.tags.map(String) : [],
  };
}

export function normalizeCameraListResponse(raw) {
  return {
    cameras: Array.isArray(raw.cameras) ? raw.cameras.map(normalizeCamera) : [],
  };
}
EOF

cat > "$PROJECT_ROOT/apps/client/dtos/camBotDtos.js" <<'EOF'
// Code generated by apps/generate-dtos.sh.
// Source of truth: apps/contracts/openapi/cambot-api.yaml

export function normalizeOperatorAction(raw) {
  return {
    id: String(raw.id),
    cameraId: String(raw.cameraId),
    promptId: raw.promptId ?? null,
    sortRunId: raw.sortRunId ?? null,
    rank: Number(raw.rank ?? 0),
    score: Number(raw.score ?? 0),
    severity: String(raw.severity ?? "low"),
    classification: String(raw.classification ?? "unknown"),
    reason: String(raw.reason ?? ""),
    recommendedAction: String(raw.recommendedAction ?? ""),
    operatorPriority: String(raw.operatorPriority ?? "normal"),
    status: String(raw.status ?? "open"),
    snapshotUrl: raw.snapshotUrl ?? null,
    createdAt: raw.createdAt ?? null,
    updatedAt: raw.updatedAt ?? null,
  };
}

export function normalizeOperatorActionsResponse(raw) {
  return {
    actions: Array.isArray(raw.actions) ? raw.actions.map(normalizeOperatorAction) : [],
  };
}

export function normalizeStats(raw) {
  return {
    operatorActionsOpen: Number(raw.operatorActionsOpen ?? 0),
    operatorActionsAcknowledged: Number(raw.operatorActionsAcknowledged ?? 0),
    operatorActionsResolved: Number(raw.operatorActionsResolved ?? 0),
    operatorActionsDismissed: Number(raw.operatorActionsDismissed ?? 0),
    workerRunsToday: Number(raw.workerRunsToday ?? 0),
    geminiCallsToday: Number(raw.geminiCallsToday ?? 0),
    skippedRunsDueToRateLimitToday: Number(raw.skippedRunsDueToRateLimitToday ?? 0),
    lastWorkerRunAt: raw.lastWorkerRunAt ?? null,
    lastSuccessfulWorkerRunAt: raw.lastSuccessfulWorkerRunAt ?? null,
  };
}
EOF

echo "DTO generation complete."
